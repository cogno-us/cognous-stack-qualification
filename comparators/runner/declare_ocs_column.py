#!/usr/bin/env python3
"""Writes or checks the declarations of the protected-destination column (comparators/runner/ocs-column-declarations.json and
the human-readable table next to it).

The declarations are produced by the rules of ocs_column.py from the steps of each executable scenario of the plan file and from
sentences that were published before the plan; no result, no expected status and no behaviour of any configuration is read.

Usage:
  python3 comparators/runner/declare_ocs_column.py --write      write both files from the plan file
  python3 comparators/runner/declare_ocs_column.py --check      exit 1 when the committed files differ from a fresh computation
  options: --plan <plan.json>  --json <path>  --table <path>
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))
from comparators.runner import ocs_column as O  # noqa: E402

DEFAULT_PLAN = REPO / 'comparators/wiki/plans/wiki-subset-plan.json'
DEFAULT_JSON = HERE / 'ocs-column-declarations.json'
DEFAULT_TABLE = HERE / 'ocs-column-declarations.md'

RULES = [
    'R1. A step is applied to the destination exactly when its declared interface can express it (ocs_column.classify_step). A scenario with a '
    'step that cannot be expressed is declared NOT-EXPRESSIBLE, citing the interface item that lacks the field, operation or state and the '
    'sentence of the case that the scenario was written from.',
    'R2. Expressible steps: execute through the eight request fields to the one target that a destination grant pins; a clock step; the '
    'zero-argument controls revoke, fence, rotate, reopen and break_audit; revoke_grant:<grant> for a grant of the declared world. Every other '
    'control, and every call to another target, has no counterpart.',
    'R3. A scenario whose steps are all expressible but whose question is carried in issuer_claims or in payload content (which the destination '
    'records and never reads) is declared NOT-CLAIMED only when a sentence published before the plan states what OCS does not claim for the case '
    '(a not-claimed sentence of the applicability file at its pinned revision, or amendment 39); it is still run and its observation is retained '
    'apart from the scored results (amendment 74). Without such a sentence the declaration would be void and the scenario is ASKED.',
    'R4. Any other scenario is ASKED and scored by the same oracle as the comparator applications.',
    'R5. A declaration does not depend on the expected statuses of the scenario and is made before any result exists.',
]

def world_mapping(grant_count, largest_scenario_calls):
    return (
        'Every grant of the declared Wiki world is provisioned at the destination the way the registered fixture provisions its own grant: policy '
        '"%s", target "%s", principal "%s", the lifetime (expires_at) and the effect count (max_effects) of the world\'s grant record, one fence '
        'generation. A destination grant pins one target, so a call to any other target is outside every grant (rule R2). The %d grants that are '
        'provisioned in addition to the registered one use %d of the 128 admission attempts of the first interval of 60 clock units (interface '
        'item DEST-INGRESS); the largest executable scenario of the plan file makes %d calls.'
        % (O.PINNED_POLICY, O.PINNED_TARGET, O.FIXTURE_PRINCIPAL, grant_count, grant_count, largest_scenario_calls))


def compute(plan_path):
    plan_bytes = Path(plan_path).read_bytes()
    plan = json.loads(plan_bytes)
    applicability = O.load_applicability()
    grant_ids = O._world_grant_ids()
    records = [O.declare(case, applicability, grant_ids) for case in plan['cases']]
    counts = {O.STATUS_ASKED: 0, O.STATUS_NE: 0, O.STATUS_NC: 0}
    per_case = {}
    total_per_case = {}
    for c in plan['cases']:
        total_per_case[c['wiki_case_id']] = total_per_case.get(c['wiki_case_id'], 0) + 1
    for c in plan['non_executed']:
        total_per_case[c['wiki_case_id']] = total_per_case.get(c['wiki_case_id'], 0) + 1
    for r in records:
        counts[r['status']] += 1
        row = per_case.setdefault(r['case'], {O.STATUS_ASKED: 0, O.STATUS_NE: 0, O.STATUS_NC: 0})
        row[r['status']] += 1
    plan_level = [dict(scenario=c['id'], case=c['wiki_case_id'], plan_state=c['state'], origin=c['origin'], reason_code=c.get('reason_code'))
                  for c in plan['non_executed']]
    out = {
        'schema': 'cognous.ocs-column-declarations/1',
        'scope_text': plan['scope_text'],
        'configuration': O.OCS_PROFILE,
        'status': ('Declarations of the protected-destination column for the Wiki subset (amendment 76; PR-1 and section 7 of the pre-registration; '
                   'rule of the draft amendment 79). Generated by comparators/runner/declare_ocs_column.py from the executable scenarios of the plan '
                   'file and from sentences that were published before it. No scenario of any set has been run on any configuration; no result, '
                   'expected status or behaviour of a configuration was read to make a declaration.'),
        'plan': {'path': 'comparators/wiki/plans/wiki-subset-plan.json', 'sha256': hashlib.sha256(plan_bytes).hexdigest(),
                 'executable_scenarios': len(plan['cases']), 'scenarios_total': plan['scenarios_total'],
                 'note': 'A declaration is valid for a scenario while its scenario_sha256 equals the digest of the scenario in the plan file. '
                         'A plan file that gains or changes scenarios needs the declarations to be generated again and reviewed.'},
        'hub': {'repo': O.HUB_REPO, 'revision': O.HUB_REVISION, 'file': O.HUB_FILE, 'file_sha256': O.HUB_FILE_SHA256},
        'applicability': {'file': O.APPLICABILITY_FILE, 'version': O.APPLICABILITY_VERSION, 'catalog_commit': O.APPLICABILITY_CATALOG_COMMIT},
        'rules': RULES,
        'world_mapping': world_mapping(len(grant_ids) - 1, max((r['executes'] for r in records), default=0)),
        'interface_items': {k: dict(description=v['description'], source=v['file'], marker=v['marker']) for k, v in O.INTERFACE.items()},
        'amendments_and_rules_cited': O.AMENDMENTS,
        'counts': {'executable_scenarios': len(plan['cases']), **counts,
                   'per_case': {k: dict(per_case[k], of=total_per_case[k]) for k in per_case}},
        'records': records,
        'plan_level_not_executed': plan_level,
    }
    return out


def render_table(decl):
    lines = ['# Declarations of the protected-destination column (Wiki subset)', '',
             'Scope text: ' + decl['scope_text'], '',
             'Generated by `comparators/runner/declare_ocs_column.py`; the data is `ocs-column-declarations.json`. Plan file `%s`, sha256 `%s`.'
             % (decl['plan']['path'], decl['plan']['sha256']), '',
             'Nothing here was derived from a result. NOT-EXPRESSIBLE: the destination interface lacks a field, operation or state that a step '
             'needs. NOT-CLAIMED: all steps can be applied, a sentence published before the plan states what OCS does not claim; the scenario is '
             'run and the observation retained apart from the scored results. ASKED: scored by the same oracle as the comparator applications.', '',
             '## Counts (executable scenarios of the plan file)', '',
             '| Asked | Not expressible | Not claimed | Executable scenarios |', '| ---: | ---: | ---: | ---: |',
             '| %d | %d | %d | %d |' % (decl['counts'][O.STATUS_ASKED], decl['counts'][O.STATUS_NE], decl['counts'][O.STATUS_NC],
                                         decl['counts']['executable_scenarios']), '',
             'Scenarios of the plan file without executable steps (%d) are not asked of any configuration and are listed at the end.'
             % len(decl['plan_level_not_executed']), '',
             '## Per case', '', '| Case | Asked | Not expressible | Not claimed | Scenarios in the case |', '| --- | ---: | ---: | ---: | ---: |']
    for case, row in decl['counts']['per_case'].items():
        lines.append('| %s | %d | %d | %d | %d |' % (case, row[O.STATUS_ASKED], row[O.STATUS_NE], row[O.STATUS_NC], row['of']))
    lines += ['', '## World mapping', '', decl['world_mapping'], '', '## Rules', ''] + ['- ' + r for r in decl['rules']]
    lines += ['', '## Interface items cited', '', '| Item | Description | Source | Marker text |', '| --- | --- | --- | --- |']
    for k, v in decl['interface_items'].items():
        lines.append('| %s | %s | `%s` | `%s` |' % (k, v['description'].replace('|', '/'), v['source'], v['marker'].replace('|', '/')))
    lines += ['', '## Per scenario', '',
              '| Scenario | Status | Code | Blocking steps | Interface items | Not-claimed sentence or amendment | Reason |', '| --- | --- | --- | --- | --- | --- | --- |']
    for r in decl['records']:
        blocking = ', '.join('#%d %s' % (b['step'], b['action']) for b in r.get('blocking_steps', [])[:4])
        more = len(r.get('blocking_steps', [])) - 4
        if more > 0:
            blocking += ' (+%d)' % more
        refs = []
        for c in r['citations']:
            if c['kind'] == 'not_claimed_sentence':
                refs.append('applicability %s %s' % (c['case'], 'not_claimed'))
            elif c['kind'] == 'amendment':
                refs.append('amendment ' + c['ref'])
        lines.append('| %s | %s | %s | %s | %s | %s | %s |' % (r['scenario'], r['status'], r['reason_code'], blocking or '-',
                                                              ', '.join(r['interface_items']), '; '.join(refs) or '-', r['reason'].replace('|', '/')))
    lines += ['', '## Scenarios without executable steps in the plan file', '',
              '| Scenario | State in the plan file | Origin | Code |', '| --- | --- | --- | --- |']
    for p in decl['plan_level_not_executed']:
        lines.append('| %s | %s | %s | %s |' % (p['scenario'], p['plan_state'], p['origin'], p['reason_code'] or '-'))
    return '\n'.join(lines) + '\n'


def dumps(decl):
    return json.dumps(decl, indent=1, ensure_ascii=False) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--plan', type=Path, default=DEFAULT_PLAN)
    ap.add_argument('--json', type=Path, default=DEFAULT_JSON)
    ap.add_argument('--table', type=Path, default=DEFAULT_TABLE)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    decl = compute(args.plan)
    want_json, want_table = dumps(decl), render_table(decl)
    if args.write:
        args.json.write_text(want_json)
        args.table.write_text(want_table)
        print('written: %d records (asked %d, not expressible %d, not claimed %d)'
              % (len(decl['records']), decl['counts'][O.STATUS_ASKED], decl['counts'][O.STATUS_NE], decl['counts'][O.STATUS_NC]))
        return 0
    bad = [str(p) for p, want in ((args.json, want_json), (args.table, want_table)) if not p.exists() or p.read_text() != want]
    if bad:
        print('not current: ' + ', '.join(bad))
        return 1
    print('current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
